"""Regenerate the frontend dashboard test fixture from the Phase 7 pipeline fakes.

    cd backend && python -m tests.make_dashboard_fixture

Runs the mocked LLM-enabled pipeline (no network, no keys) and writes the
run state, consolidated result and event list exactly as the API serialises
them, so the frontend types and tests follow the backend schemas. The data is
test-fake data, not real competitor evidence.
"""

from __future__ import annotations

import asyncio
import json
import tempfile
from pathlib import Path

from app.core.config import Settings
from app.services.catalogue import load_catalogue
from tests.discovery_fakes import FakeLLM
from tests.intelligence_fakes import FakeExtractLLM
from tests.pipeline_fakes import harness
from tests.test_discovery_agent import CLASSIFICATIONS, PLAN
from tests.test_intelligence_agent import EXTRACTIONS, PROPOSALS

OUT = Path(__file__).resolve().parents[2] / "frontend" / "src" / "test" / "fixtures" / "llm-run.json"


def main() -> None:
    catalogue = load_catalogue(Settings().catalogue_path)
    with tempfile.TemporaryDirectory() as tmp:
        h = harness(catalogue, Path(tmp), llm1=lambda: FakeLLM(PLAN, CLASSIFICATIONS),
                    llm2=lambda: FakeExtractLLM(EXTRACTIONS, PROPOSALS))  # fmt: skip
        run, result, events = asyncio.run(h.run(product_ids=["SB-001"]))
    data = {
        "_note": "Generated by backend/tests/make_dashboard_fixture.py from mocked pipeline fakes. Not real data.",
        "run": run.model_dump(mode="json"),
        "result": result.model_dump(mode="json"),
        "events": [e.model_dump(mode="json") for e in events],
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(data, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(events)} events, run {run.status.value})")


if __name__ == "__main__":
    main()
